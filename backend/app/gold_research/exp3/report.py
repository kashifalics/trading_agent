"""docs/reports/XAUUSD_EXPERIMENT3.md from the stored experiment-3 files (nothing hand-entered). Analysis only."""
import json

import numpy as np

from app.gold_research.exp2 import financing as F
from app.gold_research.exp3 import data as D
from app.gold_research.exp3 import run
from app.gold_research.exp3 import setups as SU


def _f(x, d=3, sign=True):
    if x is None or (isinstance(x, float) and not np.isfinite(x)):
        return "-"
    return f"{x:+.{d}f}" if sign else f"{x:.{d}f}"


def render(symbol: str) -> str:
    o = run.out_dir(symbol)
    sp = D.load(symbol)
    pre = run.load_preregistration(symbol)
    dev = json.loads((o / "development.json").read_text()) if (o / "development.json").exists() else None
    fs = F.fred_status()
    L = [f"# {symbol} experiment 3: well-powered structural setups on H1 and H4", "",
         "_Generated by `python -m app.gold_research.exp3 report` from stored results. Plan: `docs/research/EXPERIMENT_3_PLAN.md` "
         "(route 1). Analysis only._", "",
         "## Data use", "",
         f"* **Development:** {sp['development']['start'][:10]} to {sp['development']['end_exclusive'][:10]} (exclusive): the whole "
         "training period.",
         f"* **Not used:** the experiment-1 validation period ({sp['not_used']['experiment1_validation'][0][:10]} to "
         f"{sp['not_used']['experiment1_validation'][1][:10]}, results seen) and the sealed final test (from "
         f"{sp['sealed_final_test_from'][:10]}, not read).",
         f"* Split hash `{sp['sha256'][:16]}`; pre-registration hash `{pre['sha256'][:16]}` (code commit "
         f"`{(pre.get('code_commit') or 'n/a')[:10]}`), written before any outcome was computed.", "",
         "## Fixes and definitions", "",
         "* F1 daily-break gaps are scheduled closures; F2 levels refreshed every trading week; F3 the band nearest the breakout close;",
         "  F4 gap list limited to the development period; F5 the wider definitions below.",
         ""]
    L += ["| Setup | Definition |", "|---|---|"] + [f"| {k} | {v} |" for k, v in SU.SETUPS.items()]
    L += ["", "## Execution and costs (identical for setups and controls)", "",
          f"* Limit order at the signal close, live {run.WAIT} candles; conservative fill (trade through by the signal-time spread); "
          f"stop = far edge + {run.BUFFER_ATR} ATR; main target {run.PRIMARY_TARGET:g}R; time stop "
          + ", ".join(f"{tf} {h} candles" for tf, h in run.PRIMARY_HOLD.items()) + ".",
          "* Real Dukascopy bid/ask; financing $0.10 per ounce per night (main), also no financing and the FRED proxy when available "
          f"(FRED data: {'available' if fs['available'] else 'NOT available'}).",
          "* Long and short are pooled per test; every trade is compared with random limit orders of the same direction, distance, "
          "width, session, volatility and year.", "",
          f"## Power gate (counts only, before outcomes; minimum {pre['n_min']:,} development fills)", "",
          "| Setup | TF | Orders | Estimated fills | Long | Short | Status |", "|---|---|---|---|---|---|---|"]
    for t in pre["tests"]:
        L.append(f"| {t['setup']} | {t['tf']} | {t['orders']:,} | {t['est_fills']:,} | {t['long']:,} | {t['short']:,} | {t['status']} |")
    L.append("")
    if dev:
        L += ["## Development results", "",
              f"{dev['tests_run']} tests run. The deflated Sharpe ratio counts {dev['trials_counted_for_deflated_sharpe']:,} trials ("
              + ", ".join(f"{k} {v:,}" for k, v in dev["prior_trials"].items()) + f", experiment 3 {dev['tests_run']}).", "",
              "| TF | Setup | Trades (L/S) | Win % | Mean R | Control R | Edge +/- SE | q | Slip $0.10 | Spread x1.5 | No financing | "
              "DSR | Years + | Halves | Status |", "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for r in dev["rows"]:
            m, st = r.get("main") or {}, r.get("stress") or {}
            g = lambda k: _f((st.get(k) or {}).get("mean")) if st.get(k) else "n/a"  # noqa: E731
            hv = " / ".join(f"{k} {_f(v)}" for k, v in sorted((r.get("halves") or {}).items()))
            L.append(f"| {r['tf']} | {r['setup']} | {r['trades']:,} ({r['long']:,}/{r['short']:,}) | "
                     f"{_f(100 * m['win_rate'], 0, False) if m.get('n') else '-'} | {_f(m.get('mean_r'))} | {_f(m.get('ctrl_mean_r'))} | "
                     f"{_f(m.get('edge'))} +/- {_f(m.get('edge_se'), 3, False)} | {_f(r.get('q'), 3, False)} | {g('slippage_0.10')} | "
                     f"{g('spread_x1.5')} | {g('no_financing')} | {_f(r.get('dsr'), 3, False)} | "
                     f"{_f(100 * r.get('share_positive_years', 0), 0, False)}% | {hv} | {r['status']} |")
        L += ["", f"**Frozen candidates:** {len(dev['candidates'])}"
              + (": " + "; ".join(f"{c['tf']} {c['setup']}" for c in dev["candidates"]) if dev["candidates"]
                 else " (nothing passed every criterion; the sealed period stays sealed)."), ""]
    L += ["## Limitations", "",
          "* One data source (Dukascopy); a broker's spreads, stop rules, limit-order queue and swaps differ.",
          "* Development results are hypotheses: experiment 3 was designed after experiments 1-2 and the diagnostic. Only the sealed "
          "test (with the owner's separate approval) or forward paper trading can confirm a candidate.",
          "* The power gate counts fills at candle level (the simulator can still reject a few at minute level)."]
    return "\n".join(L) + "\n"


def write(symbol: str, log=print) -> None:
    p = run.report_path(symbol)
    p.write_text(render(symbol), encoding="utf8")
    log(f"report written: {p}")
