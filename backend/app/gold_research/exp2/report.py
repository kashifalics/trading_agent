"""docs/reports/XAUUSD_EXPERIMENT2.md from the stored experiment-2 results (nothing hand-entered). Analysis only."""
import json

import numpy as np

from app.gold_research.exp2 import data as D
from app.gold_research.exp2 import financing as F
from app.gold_research.exp2 import run


def _f(x, d=3, sign=True):
    if x is None or (isinstance(x, float) and not np.isfinite(x)):
        return "-"
    return f"{x:+.{d}f}" if sign else f"{x:.{d}f}"


def render(symbol: str) -> str:
    o = run.out_dir(symbol)
    dev = json.loads((o / "development.json").read_text()) if (o / "development.json").exists() else None
    scr = json.loads((o / "screening.json").read_text()) if (o / "screening.json").exists() else None
    sp = D.load(symbol)
    fs = F.fred_status()
    L = [f"# {symbol} experiment 2: structural limit entries, longer holds, bid/ask and financing costs", "",
         "_Generated by `python -m app.gold_research.exp2 report` from stored results. Plan: `docs/research/EXPERIMENT_2_PLAN.md`. "
         "Analysis only._", "",
         "## Data use", "",
         f"* **Development:** {sp['development']['start'][:10]} to {sp['development']['end_exclusive'][:10]} (exclusive).",
         f"* **Screening:** {sp['screening']['start'][:10]} to {sp['screening']['end_exclusive'][:10]}. **This period was examined in "
         "experiment 1, in aggregate, so it is screening and comparison only, not independent validation.**",
         "* **Not used:** the experiment-1 validation period (its results shaped this experiment) and the sealed final test, which was not "
         "read.",
         f"* Split file hash `{sp['sha256'][:16]}`.", "",
         "## Execution and cost assumptions (identical for setups and controls)", "",
         f"* **Entry:** a limit order placed at the close of the signal candle, live for {run.WAIT} candles, cancelled if a candle closes "
         "beyond the far edge first.",
         "* **Conservative fill:** the ask (longs) or bid (shorts) must trade beyond the limit by the spread measured at the signal candle; "
         "the fill minute is found on 1-minute data. In the fill minute only adverse prices count.",
         f"* **Stop:** far edge + {run.BUFFER_ATR} ATR, at least 0.25 ATR from the fill. Exits at the bid (longs) or ask (shorts); the stop "
         "candle is replayed minute by minute; a stop minute that opens beyond the stop fills at that open.",
         f"* **Targets and holds:** {', '.join(f'{k:g}R' for k in run.TARGETS)} (main {run.PRIMARY_TARGET:g}R); time stop "
         f"{', '.join(f'{tf} {h} candles' for tf, h in run.PRIMARY_HOLD.items())}; other holds are description only.",
         "* **Gaps:** a trade is excluded only if an unscheduled gap (30+ minutes, not a US holiday) starts while it is actually open.",
         "* **Financing:** nights held (17:00 New York rollovers, Friday counting 3) times the scenario cost. **Main scenario:** fixed $0.10 "
         "per ounce per night. Also reported: no financing; and a FRED-based proxy (fed funds + 2.5% for longs; 2.5% − fed funds for "
         "shorts). The proxy is **not** a historical broker swap rate.",
         f"* **FRED data:** {'available, ' + str(fs['rows']) + ' daily rows ' + fs['first'] + ' to ' + fs['last'] if fs['available'] else 'NOT available: ' + fs['note']}.",
         "* **Spread:** Dukascopy's own bid/ask on every trade; stress tests add 1.5× spread or $0.10 slippage per side.", ""]
    if dev:
        L += ["## Development (2003-2014)", "",
              f"{dev['pre_registered_tests']} pre-registered tests (6 setups × 3 timeframes × 2 directions), {dev['tests']} with at least "
              f"{run.MIN_TRADES} trades. **Multiple testing:** BH over these tests; the deflated Sharpe ratio counts all "
              f"{dev['trials_counted_for_deflated_sharpe']:,} trials so far (experiment 1: "
              + ", ".join(f"{k} {v:,}" for k, v in dev['prior_trials'].items()) + f"; experiment 2: {dev['pre_registered_tests']}).", "",
              "A candidate must pass **every** criterion:",
              "* BH q < 0.10 with a positive edge over matched controls;",
              "* mean R > 0 with p < 0.05 under the main costs;",
              "* still positive with $0.10 slippage per side, and with 1.5× spread;",
              "* deflated Sharpe probability > 0.95;",
              "* positive in at least 60% of development years.", "",
              "| TF | Setup | Dir | Trades | Win % | Mean R (main costs) | Control R | Edge +/- SE | q | Slip $0.10 | Spread x1.5 | No financing | FRED proxy | DSR | Positive years | Status |",
              "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for r in dev["rows"]:
            m = r.get("main") or {}
            st = r.get("stress") or {}
            g = lambda k: _f((st.get(k) or {}).get("mean")) if st.get(k) else "n/a"  # noqa: E731
            L.append(f"| {r['tf']} | {r['setup']} | {r['direction']} | {r['trades']:,} | {_f(100 * m['win_rate'], 0, False) if m.get('n') else '-'} | "
                     f"{_f(m.get('mean_r'))} | {_f(m.get('ctrl_mean_r'))} | {_f(m.get('edge'))} +/- {_f(m.get('edge_se'), 3, False)} | "
                     f"{_f(r.get('q'), 3, False)} | {g('slippage_0.10')} | {g('spread_x1.5')} | {g('no_financing')} | {g('fred_proxy')} | "
                     f"{_f(r.get('dsr'), 3, False)} | {_f(100 * r.get('share_positive_years', 0), 0, False)}% | {r['status']} |")
        L += ["", f"**Frozen candidates:** {len(dev['candidates'])}" + (": " + "; ".join(f"{c['tf']} {c['setup']} {c['direction']}" for c in dev["candidates"])
                                                                       if dev["candidates"] else " (nothing passed every criterion)."), ""]
    if scr:
        L += ["## Screening (2015-2020-02; previously examined, NOT independent)", "",
              "| TF | Setup | Dir | Trades | Win % | Mean R | Edge | Holm p | Verdict |", "|---|---|---|---|---|---|---|---|---|"]
        for r in scr["rows"]:
            s = r["screen"]
            L.append(f"| {r['tf']} | {r['setup']} | {r['direction']} | {s.get('n', 0):,} | {_f(100 * s.get('win_rate', 0), 0, False)} | "
                     f"{_f(s.get('mean_r'))} | {_f(s.get('edge'))} | {_f(r.get('holm_p'), 4, False)} | {r['verdict']} |")
        L.append("")
    L += ["## Limitations", "",
          "* One data source (Dukascopy); a broker's spreads, minimum stop distance, limit-order queue and swap differ.",
          "* The financing proxy is an assumption, not historical broker swaps; the fixed $0.10/night is a round-number scenario.",
          "* The screening period was seen in aggregate in experiment 1; passing it is screening, not proof. Only the sealed final test "
          "(with your separate approval) or forward paper trading can confirm anything."]
    return "\n".join(L) + "\n"


def write(symbol: str, log=print) -> None:
    p = run.report_path(symbol)
    p.write_text(render(symbol), encoding="utf8")
    log(f"report written: {p}")
