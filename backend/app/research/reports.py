"""Markdown report renderers. Every number is read from stored experiments; prose is limited to rule-derived statements."""
from app.research.strategy_eval import COST_SCENARIOS, round_trip_cost_frac

SCEN_ORDER = ["zero_cost", "optimistic", "base", "stress"]


def f(v, d=2, pct=False, sign=False):
    if v is None or (isinstance(v, float) and v != v):
        return "—"
    s = f"{v:+.{d}f}" if sign else f"{v:.{d}f}"
    return s + ("%" if pct else "")


def fp(v, d=1):
    return "—" if v is None else f"{100 * v:.{d}f}%"


def _cost_table() -> list[str]:
    out = ["| Scenario | Fee / side | Spread (full) | Slippage / market fill | Round-trip total |", "|---|---|---|---|---|"]
    for k in SCEN_ORDER:
        c = COST_SCENARIOS[k]
        out.append(f"| `{k}` | {c.get('commission_pct', 0)}% | {c.get('spread_pct', 0)}% | {c.get('slippage_pct', 0)}% | "
                   f"{100 * round_trip_cost_frac(k):.3f}% |")
    return out


def _tm_row(label, m):
    if not m or not m.get("n_trades"):
        return f"| {label} | 0 | — | — | — | — | — |"
    return (f"| {label} | {m['n_trades']} | {fp(m.get('win_rate'))} | {f(m.get('profit_factor'))} | "
            f"{f(m.get('expectancy_r'), 3, sign=True)} | {f(m.get('total_r'), 1, sign=True)} | {f(m.get('avg_bars_held'), 1)} |")


def render_backtest(tf: str, scen: dict, baselines: dict, snap: dict, exp_ids: dict, hours_per_bar: int) -> str:
    base = scen["base"]
    o = [f"# BTCUSDT {tf} — rule-based engine backtest", "",
         "_Generated by `python -m app.research.run_milestone report` from stored experiments "
         f"({', '.join(f'{k}=#{v}' for k, v in exp_ids.items())}). Nothing on this page is hand-entered._", "",
         "## Dataset", "",
         f"* Binance spot BTCUSDT {tf}, candle snapshot **`{snap['snapshot_id']}`** ({snap['hash']}).",
         f"* {snap['n_candles']:,} completed candles, {snap['first_ts']} → {snap['last_ts']}.",
         f"* Evaluated period (after the strategy's 120-bar warm-up): {base['period']['start']} → {base['period']['end']} "
         f"({base['period']['bars']:,} bars).", "",
         "## Strategy and execution assumptions", "",
         "* Strategy: `decision_engine` — the production BUY/SELL/WAIT policy restricted to price-action evidence of this single "
         "timeframe (no analogues, ML or multi-timeframe). **Parameters are the library defaults; nothing was tuned on this data.**",
         "* A signal is generated from bars up to and including bar *i*; the order fills at the **open of bar i+1** (never the signal "
         "close). Evaluated on every bar while flat (`eval_every=1`).",
         "* The plan's *entry zone* is not used: entries are market orders at the next open. Stop and first target come from the plan.",
         "* If one bar contains both stop and target, **the stop is assumed hit first**. Gaps through a stop fill at the open.",
         "* Sizing: 1% of current equity risked per trade (stop distance), leverage capped at 20×, one position at a time, "
         "forced exit after 200 bars or at end of data.",
         "* The strategy's internal data-quality gate is held at ≥ 0.9 (history is complete by construction here).",
         "* Costs are percentages of price so they stay realistic across a 16k → 120k price history:", ""]
    o += _cost_table()
    o += ["", "Binance spot's standard taker fee is 0.10% per side (0.075% with BNB discount); BTCUSDT's quoted spread is typically "
          "a tick or two, so the spread input is deliberately conservative. **`base` is the headline scenario.**", "",
          "## Results by cost scenario (same signals, different costs)", "",
          "| Scenario | Trades | Win rate | Profit factor | Expectancy (R) | 95% bootstrap CI (R) | Net return | Max DD | Sharpe | Avg bars held | Costs paid |",
          "|---|---|---|---|---|---|---|---|---|---|---|"]
    for k in SCEN_ORDER:
        r = scen.get(k)
        if not r:
            continue
        m, sg = r["metrics"], r["significance"]
        ci = sg.get("boot_ci95")
        o.append(f"| `{k}` | {r['n_trades']} | {fp(m.get('win_rate'))} | {f(m.get('profit_factor'))} | {f(m.get('expectancy_r'), 3, sign=True)} | "
                 f"{('[' + f(ci[0], 3, sign=True) + ', ' + f(ci[1], 3, sign=True) + ']') if ci else '—'} | {f(m.get('total_return_pct'), 1, True, True)} | "
                 f"{f(m.get('max_drawdown_pct'), 1, True)} | {f(m.get('sharpe_annualized'))} | {f(r['overall'].get('avg_bars_held'), 1)} | "
                 f"{f(m.get('total_costs'), 0)} |")
    o += ["", "R = P&L ÷ initial risk (stop distance). `zero_cost` is the gross signal quality; the gap to `base` is the cost drag.", "",
          "## Headline (`base` costs)", "", f"**Verdict: {base['verdict']}.**", ""]
    sg = base["significance"]
    if "p_edge_gt_0" in sg:
        o += [f"* Mean net expectancy {f(sg['mean_r'], 3, sign=True)} R over {sg['n']} trades; one-sided t-test "
              f"p(edge > 0) = {sg['p_edge_gt_0']:.3f}, p(edge < 0) = {sg['p_edge_lt_0']:.3f}.",
              f"* Share of walk-forward folds with positive expectancy: {fp(base['folds_positive_share'], 0)}."]
    o += [f"* Exit reasons: {base.get('exits')}", f"* Signals skipped (stop on wrong side after a gap): {base['skipped_signals']}.", "",
          "## Walk-forward folds (`base` costs)", "",
          "Chronological, non-overlapping windows of the evaluated period (the rule set has no fitted parameters, so each window is a "
          "genuine out-of-sample test of the fixed rules). Assigned by signal time.", "",
          "| Fold | From | To | Trades | Win rate | PF | Expectancy (R) | Σ R | Avg bars |", "|---|---|---|---|---|---|---|---|---|"]
    for fo in base["folds"]:
        o.append(f"| {fo['fold']} | {fo['start'][:10]} | {fo['end'][:10]} | {fo['n_trades']} | {fp(fo.get('win_rate'))} | "
                 f"{f(fo.get('profit_factor'))} | {f(fo.get('expectancy_r'), 3, sign=True)} | {f(fo.get('total_r'), 1, sign=True)} | {f(fo.get('avg_bars_held'), 1)} |")
    o += ["", "## Long vs short and market regimes (`base` costs)", "",
          "| Slice | Trades | Win rate | PF | Expectancy (R) | Σ R | Avg bars |", "|---|---|---|---|---|---|---|"]
    o.append(_tm_row("Long", base["by_direction"]["long"]))
    o.append(_tm_row("Short", base["by_direction"]["short"]))
    for grp, label in (("volatility", "Volatility (ATR% tercile)"), ("structure_trend", "Structure trend"), ("vs_sma200", "Close vs SMA200")):
        for name, m in base["by_regime"][grp].items():
            o.append(_tm_row(f"{label}: {name}", m))
    o += ["", f"_Volatility terciles use full-sample ATR% edges {base['vol_terciles_atr_pct']} — descriptive only, never used by the strategy._", "",
          "## Baselines (`base` costs, same execution model and period)", "",
          "| Baseline | Trades | Net return | Max DD | Sharpe | Notes |", "|---|---|---|---|---|---|"]
    bnh, trend = baselines["buy_and_hold"], baselines["sma200_trend_long_flat"]
    mac, rnd = baselines["ma_cross_ema20_50"], baselines["random_entry_mean_of_seeds"]
    bm = base["metrics"]
    o += [f"| **Rule engine (this report)** | {base['n_trades']} | {f(bm.get('total_return_pct'), 1, True, True)} | {f(bm.get('max_drawdown_pct'), 1, True)} | {f(bm.get('sharpe_annualized'))} | 1% risk per trade |",
          "| No trade | 0 | 0.0% | 0.0% | — | cash |",
          f"| Buy & hold | 1 | {f(bnh['total_return_pct'], 1, True, True)} | {f(bnh['max_drawdown_pct'], 1, True)} | {f(bnh['sharpe_annualized'])} | 100% exposure; **not risk-matched** to the strategy |",
          f"| SMA200 trend (long/flat) | {trend['n_trades']} | {f(trend['total_return_pct'], 1, True, True)} | {f(trend['max_drawdown_pct'], 1, True)} | {f(trend['sharpe_annualized'])} | exposure {f(trend['exposure_pct'], 0, True)} |",
          f"| EMA20/50 cross (engine, 1% risk) | {mac['n_trades']} | {f(mac['total_return_pct'], 1, True, True)} | {f(mac['max_drawdown_pct'], 1, True)} | {f(mac['sharpe_annualized'])} | expectancy {f(mac['expectancy_r'], 3, sign=True)} R, PF {f(mac['profit_factor'])} |",
          f"| Random entries (engine, mean of {rnd['seeds']} seeds) | {rnd['n_trades_mean']:.0f} | {f(rnd['return_pct_mean'], 1, True, True)} | {f(rnd['max_drawdown_pct_mean'], 1, True)} | — | range {f(rnd['return_pct_min'], 1, True, True)} … {f(rnd['return_pct_max'], 1, True, True)}; expectancy {f(rnd['expectancy_r_mean'], 3, sign=True)} R |",
          "", "Buy-and-hold and the strategy are not comparable in raw return (different exposure and risk). Compare drawdown and Sharpe, and "
          "use random entries as the cost-drag reference: a strategy has no demonstrated skill unless it beats that distribution.", "",
          "## Limitations", "",
          "* One instrument and one historical path; folds are serially dependent and the sample covers a limited set of regimes.",
          "* No holiday/maintenance modelling is needed for 24/7 BTCUSDT, but exchange outages and order-book depth are not modelled.",
          "* Results are for fixed default rules. Any later parameter change must be validated on a period not used here.", ""]
    return "\n".join(o)


def _ml_row(label, r, cost_label):
    t = r.get("oos_trades", {})
    bs = r.get("brier_skill")
    cal = (r.get("calibration") or {}).get("ece")
    return (f"| {label} | {cost_label} | {r.get('n_oos_rows', 0):,} | {t.get('n_trades', 0)} | {fp(t.get('win_rate'))} | "
            f"{f(t.get('profit_factor'))} | {f(t.get('expectancy_r'), 3, sign=True)} | "
            f"{('[' + f(t.get('expectancy_r_ci_low'), 3, sign=True) + ', ' + f(t.get('expectancy_r_ci_high'), 3, sign=True) + ']') if t.get('expectancy_r_ci_low') is not None else '—'} | "
            f"{f(bs, 4, sign=True)} | {f(cal, 3)} | {fp(r.get('prediction_coverage'), 2)} | **{r.get('status', '—').replace('_', ' ')}** |")


def render_ml(per_tf: dict) -> str:
    o = ["# BTCUSDT machine-learning evaluation", "",
         "_Generated from stored experiments. Models are evaluated, never promoted automatically: a model needs "
         "`passed_minimum_checks` (all gates below) to influence a decision or expose probabilities._", "",
         "## Protocol", "",
         "* Label: triple barrier on ATR, entry at the next open — long wins if +2 ATR is touched before −1 ATR within 24 bars, "
         "short mirrored; same-bar ambiguity resolves to the stop; classes {short-first, neither, long-first}.",
         "* 22 point-in-time features (see `ML_METHODOLOGY.md`); features/labels leak-tested.",
         "* **Expanding-window walk-forward**, 5 folds after a 40% warm-up; training rows whose label window reaches the test block are purged, plus a 6-bar embargo.",
         "* Per fold: fit on the first 80% of the purged training window, calibrate probabilities (isotonic/Platt, one-vs-rest) on the "
         "chronologically later 20%, predict the untouched test block.",
         "* Trades: long/short when the calibrated P ≥ 0.45 and leads the opposite side by ≥ 0.10; non-overlapping; costs converted to R.",
         "* Brier skill = 1 − Brier/Brier(class-prior baseline); positive means better than always predicting historical frequencies.",
         "* **Promotion gates (all required):** ≥ 1,000 OOS rows; ≥ 100 OOS trades; net expectancy CI lower bound > 0; Brier skill > 0; "
         "ECE ≤ 0.08; ≥ 60% of folds with positive expectancy; **and expectancy above every simple baseline** (≥ 30 trades).",
         "* Cost columns: `gross` = no costs (predictive information only); `base` = 0.10% fee + 0.002% spread + 0.01% slippage per side.", ""]
    for tf, d in per_tf.items():
        runs = d["runs"]
        any_run = next(iter(runs.values()))
        o += [f"## {tf}", "",
              f"Dataset snapshot **`{d['snapshot']['snapshot_id']}`** · {d['snapshot']['n_candles']:,} candles · "
              f"OOS window {any_run.get('oos_start', '—')[:10] if any_run.get('oos_start') else '—'} → "
              f"{any_run.get('oos_end', '—')[:10] if any_run.get('oos_end') else '—'} · experiments "
              f"{', '.join(f'#{i}' for i in d['exp_ids'])}", "",
              "| Model | Costs | OOS rows | Trades | Win rate | PF | Expectancy (R) | 95% CI (R) | Brier skill | ECE | Coverage | Status |",
              "|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for (algo, cost), r in runs.items():
            o.append(_ml_row(algo, r, cost))
        base_run = runs.get(("lightgbm", "base")) or any_run
        o += ["", "**Simple baselines on the identical OOS rows** (same labels, same `base` costs):", "",
              "| Baseline | Trades | Win rate | PF | Expectancy (R) | Σ R |", "|---|---|---|---|---|---|"]
        o += ["| class-prior model (always predicts historical frequencies) | 0 | — | — | — | Brier skill = 0 by definition |"]
        for name, m in (base_run.get("baselines") or {}).items():
            o.append(f"| {name} | {m.get('n_trades', 0)} | {fp(m.get('win_rate'))} | {f(m.get('profit_factor'))} | "
                     f"{f(m.get('expectancy_r'), 3, sign=True)} | {f(m.get('total_r'), 1, sign=True)} |")
        re = d.get("rule_engine")
        if re:
            o.append(f"| rule-based engine, same period (its own stops/targets) | {re.get('n_trades', 0)} | {fp(re.get('win_rate'))} | "
                     f"{f(re.get('profit_factor'))} | {f(re.get('expectancy_r'), 3, sign=True)} | {f(re.get('total_r'), 1, sign=True)} |")
        o += ["", "R is net P&L ÷ stop distance in all rows, but barrier-based rows (models, simple baselines) use the label's fixed 2:1 "
              "bracket while the rule engine uses its own plan, so only the sign/magnitude of expectancy is comparable.", "",
              "**Reasons each model is not promoted (if any):**", ""]
        for (algo, cost), r in runs.items():
            if cost == "base":
                o.append(f"* `{algo}` → {r.get('status')}: " + ("; ".join(r.get("reasons") or []) or "all gates passed"))
        lg = runs.get(("lightgbm", "base"))
        if lg and lg.get("folds"):
            o += ["", "LightGBM walk-forward folds (`base` costs):", "", "| Fold | Test from | Test to | Test rows | Trades | Expectancy (R) | Brier |", "|---|---|---|---|---|---|---|"]
            for i, fo in enumerate(lg["folds"], 1):
                o.append(f"| {i} | {fo['test_start'][:10]} | {fo['test_end'][:10]} | {fo['n_test']} | {fo.get('n_trades', 0)} | "
                         f"{f(fo.get('expectancy_r'), 3, sign=True)} | {f(fo.get('brier'), 4)} |")
        o.append("")
    return "\n".join(o)


def render_summary(ctx: dict) -> str:
    o = ["# BTCUSDT quantitative validation — summary", "",
         "_Generated from stored experiments by `python -m app.research.run_milestone report`. Statements below are rule-derived from the "
         "numbers in the detailed reports; no result was selected or tuned._", "",
         "## What was tested", "",
         "Whether the existing BTCUSDT analysis stack (price-action rule engine; LightGBM/logistic/XGBoost models) carries statistically "
         "meaningful predictive information on ≥ 3 years of Binance 1H and 4H candles, after realistic transaction costs, using "
         "chronological out-of-sample evaluation and simple baselines.", "", "## Data", ""]
    for tf, q in ctx["quality"].items():
        o.append(f"* {tf}: {q.get('complete_count', 0):,} completed candles, {q.get('first_candle', '—')[:10]} → "
                 f"{(q.get('last_completed_candle') or '—')[:10]}, coverage **{q.get('coverage_pct')}%**, "
                 f"{q.get('missing_count')} missing, {q.get('invalid_stored')} invalid. Snapshot `{ctx['snap'][tf]}`.")
    o += ["", "## Results", "",
          "| Timeframe | Evidence | Result |", "|---|---|---|"]
    for tf in ctx["bt"]:
        b = ctx["bt"][tf]["base"]
        g = ctx["bt"][tf]["zero_cost"]
        o.append(f"| {tf} | Rule engine, `base` costs | {b['n_trades']} trades, expectancy {f(b['metrics'].get('expectancy_r'), 3, sign=True)} R, "
                 f"PF {f(b['metrics'].get('profit_factor'))}, return {f(b['metrics'].get('total_return_pct'), 1, True, True)}, "
                 f"max DD {f(b['metrics'].get('max_drawdown_pct'), 1, True)} → **{b['verdict'].split(':')[0].split(' (')[0]}** |")
        o.append(f"| {tf} | Rule engine, zero costs (gross) | expectancy {f(g['metrics'].get('expectancy_r'), 3, sign=True)} R, "
                 f"PF {f(g['metrics'].get('profit_factor'))}, p(edge>0) {f(g['significance'].get('p_edge_gt_0'), 3)} |")
        bl = ctx["bl"][tf]
        o.append(f"| {tf} | Buy & hold / SMA200 trend | {f(bl['buy_and_hold']['total_return_pct'], 1, True, True)} (DD {f(bl['buy_and_hold']['max_drawdown_pct'], 1, True)}) / "
                 f"{f(bl['sma200_trend_long_flat']['total_return_pct'], 1, True, True)} (DD {f(bl['sma200_trend_long_flat']['max_drawdown_pct'], 1, True)}) |")
        o.append(f"| {tf} | Random entries (mean of {bl['random_entry_mean_of_seeds']['seeds']}) | {f(bl['random_entry_mean_of_seeds']['return_pct_mean'], 1, True, True)}, "
                 f"expectancy {f(bl['random_entry_mean_of_seeds']['expectancy_r_mean'], 3, sign=True)} R |")
    for tf, d in ctx["ml"].items():
        for algo in ("logistic", "lightgbm", "xgboost"):
            r = d["runs"].get((algo, "base"))
            if r:
                o.append(f"| {tf} | ML `{algo}` (walk-forward OOS, `base` costs) | Brier skill {f(r.get('brier_skill'), 4, sign=True)}, "
                         f"{r.get('oos_trades', {}).get('n_trades', 0)} trades, expectancy {f(r.get('oos_trades', {}).get('expectancy_r'), 3, sign=True)} R → **{r.get('status', '').replace('_', ' ')}** |")
    promoted = [(tf, a) for tf, d in ctx["ml"].items() for (a, c), r in d["runs"].items() if c == "base" and r.get("status") == "passed_minimum_checks"]
    positive = [tf for tf in ctx["bt"] if ctx["bt"][tf]["base"]["verdict"].startswith("POSITIVE")]
    o += ["", "## Conclusions (rule-derived)", "",
          f"* Rule engine showing a statistically positive net edge: **{', '.join(positive) if positive else 'none'}**.",
          f"* Models meeting every promotion gate: **{', '.join(f'{a}@{tf}' for tf, a in promoted) if promoted else 'none — all remain research-only'}**.",
          "* Predictions continue to expose **no probability** unless a calibrated model has passed the gates; the decision policy is unchanged.", "",
          "## Caveats", "",
          "* A negative or null result on one asset and one historical path is not proof that no edge exists anywhere; it shows these fixed rules/models "
          "did not demonstrate one here at these costs.",
          "* Costs dominate at hourly horizons: compare the `zero_cost` and `base` rows to see how much gross signal quality (if any) is consumed.",
          "* Multiple models/scenarios were evaluated; a single positive cell among many would need correction for multiple comparisons.",
          "* The rule engine was not changed to improve these numbers; parameters are defaults.", "",
          "## Reproducibility", "",
          "Each run is stored in the `experiments` table with its dataset snapshot id, full configuration, code hash and library versions. "
          "Re-run any of them with `python -m app.research.reproduce <experiment_id>`; it refuses to run if the stored candles no longer match "
          "the snapshot and reports any numeric difference.", "",
          "Experiments: " + ", ".join(f"#{i}" for i in ctx["exp_ids"]), ""]
    return "\n".join(o)
